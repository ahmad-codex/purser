// Copies contract ABIs from the Foundry build into the SDK, so the TypeScript packages work
// without Foundry installed. Run after `forge build`: npm run abi
import { readFileSync, writeFileSync } from 'node:fs';

const out = (file, name) => JSON.parse(readFileSync(`contracts/out/${file}/${name}.json`, 'utf8')).abi;

const abis = {
  purserAccountAbi: out('PurserAccount.sol', 'PurserAccount'),
  purserFactoryAbi: out('PurserFactory.sol', 'PurserFactory'),
  entryPointAbi: out('EntryPoint.sol', 'EntryPoint'),
};

let src = '// Generated by scripts/gen-abi.mjs from the Foundry build. Do not edit.\n';
for (const [name, abi] of Object.entries(abis)) {
  src += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync('packages/sdk/src/abi.ts', src);
console.log('wrote packages/sdk/src/abi.ts');
